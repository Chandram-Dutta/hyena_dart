import 'dart:convert';
import 'dart:io';

import 'package:analyzer/dart/analysis/utilities.dart';
import 'package:analyzer/dart/ast/token.dart';

/// Shared generated-source classification for the analyzers.
class GeneratedFiles {
  final _cache = <String, bool>{};

  /// Checks suffixes and leading comments, reading at most 8 KiB per file.
  bool contains(String path) => _cache.putIfAbsent(path, () {
    if (hasGeneratedSuffix(path)) return true;
    RandomAccessFile? file;
    try {
      file = File(path).openSync();
      return hasGeneratedHeader(
        utf8.decode(file.readSync(8192), allowMalformed: true),
      );
    } on FileSystemException {
      return false;
    } finally {
      file?.closeSync();
    }
  });

  /// Whether the path uses a conventional generated Dart suffix.
  static bool hasGeneratedSuffix(String path) =>
      path.endsWith('.g.dart') ||
      path.endsWith('.freezed.dart') ||
      path.endsWith('.mocks.dart');

  static final _marker = RegExp(
    r'^(?:GENERATED CODE - DO NOT MODIFY BY HAND|Code generated by [^\r\n]+ DO NOT EDIT\.)$',
    caseSensitive: false,
  );

  /// Matches only standalone markers in comments before the first Dart token.
  static bool hasGeneratedHeader(String source) {
    final result = parseString(
      content: source.startsWith('\uFEFF') ? source.substring(1) : source,
      throwIfDiagnostics: false,
    );
    final firstToken =
        result.unit.scriptTag?.endToken.next ?? result.unit.beginToken;
    for (
      Token? token = firstToken.precedingComments;
      token != null;
      token = token.next
    ) {
      final comment = token.lexeme;
      if (!comment.startsWith('//') &&
          !(comment.startsWith('/*') && comment.endsWith('*/'))) {
        continue;
      }
      final body = comment.startsWith('//')
          ? comment.substring(2)
          : comment.substring(2, comment.length - 2);
      if (_marker.hasMatch(body.trim())) return true;
    }
    return false;
  }
}
